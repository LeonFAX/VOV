// Функция поиска похожего места
function findCoords(placeName) {
  if (!placeName) return null;

  // Точное совпадение
  if (COORDS_DB[placeName]) return COORDS_DB[placeName];

  // Поиск по подстроке
  const lowerPlace = placeName.toLowerCase();
  for (const [key, coords] of Object.entries(COORDS_DB)) {
    const lowerKey = key.toLowerCase();
    if (lowerPlace.includes(lowerKey) || lowerKey.includes(lowerPlace)) {
      return coords;
    }
  }

  // Извлекаем город из строки
  const cityMatch = placeName.match(/г\.?\s*([А-Яа-я\s-]+)/i);
  if (cityMatch) {
    const city = cityMatch[1].trim();
    for (const [key, coords] of Object.entries(COORDS_DB)) {
      if (key.toLowerCase().includes(city.toLowerCase())) {
        return coords;
      }
    }
  }

  // Извлекаем область/край/республику
  const regionMatch = placeName.match(/([А-Яа-я\s-]+(?:область|край|республика|АССР|ССР))/i);
  if (regionMatch) {
    const region = regionMatch[1].trim();
    for (const [key, coords] of Object.entries(COORDS_DB)) {
      if (key.toLowerCase().includes(region.toLowerCase())) {
        return coords;
      }
    }
  }

  return null;
}

// Читаем данные героев из store или JSON
function loadHeroes() {
  // Попробуем найти файл с героями
  const possiblePaths = [
    path.join(__dirname, '../src/data/heroes.json'),
    path.join(__dirname, '../public/data/heroes.json'),
    path.join(__dirname, '../src/store/heroesData.ts'),
  ];

  for (const p of possiblePaths) {
    if (fs.existsSync(p)) {
      console.log('Found heroes data at:', p);
      const content = fs.readFileSync(p, 'utf8');
      // Если JSON
      if (p.endsWith('.json')) {
        return JSON.parse(content);
      }
      // Если TS/JS — извлекаем массив
      const match = content.match(/heroes\s*[:=]\s*(\[[\s\S]*?\]);?\s*$/);
      if (match) {
        return eval(match[1]);
      }
    }
  }

  return null;
}

// Генерируем JSON с координатами
function generateCoordsJson() {
  const heroes = loadHeroes();

  if (!heroes) {
    console.log('Could not load heroes data. Creating template...');
    // Создаём шаблон для ручного заполнения
    const template = {
      _description: 'Добавьте сюда координаты для мест рождения героев',
      _format: '"Точное название из birthPlace": [широта, долгота]',
      // Примеры:
      'д. Стрелковка, Калужская губерния': [54.506, 36.252],
    };

    const outputPath = path.join(__dirname, '../src/data/hero-coords.json');
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, JSON.stringify(template, null, 2));
    console.log('Created template at:', outputPath);
    return;
  }

  const coordsMap = {};
  const missing = [];

  for (const hero of heroes) {
    const place = hero.birthPlace;
    if (!place) continue;

    const coords = findCoords(place);
    if (coords) {
      coordsMap[place] = coords;
    } else {
      missing.push(place);
    }
  }

  // Сохраняем найденные координаты
  const outputPath = path.join(__dirname, '../src/data/hero-coords.json');
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, JSON.stringify(coordsMap, null, 2));

  console.log(`\n✅ Generated coords for ${Object.keys(coordsMap).length} places`);
  console.log(`❌ Missing coords for ${missing.length} places:`);
  missing.forEach(p => console.log(`   - "${p}"`));
  console.log(`\n📁 Saved to: ${outputPath}`);
  console.log('\n💡 Tip: Add missing places to COORDS_DB in this script and re-run');
}

generateCoordsJson();

// Helper: find the last front line entry <= given date
export function getFrontLineDataForDate(date: Date): FrontLineData {
  const sorted = [...frontLineData].sort((a, b) => a.date.getTime() - b.date.getTime());
  let prev = sorted[0];
  for (const entry of sorted) {
    if (entry.date.getTime() <= date.getTime()) prev = entry;
    else break;
  }
  return prev || sorted[0];
}

function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t;
}

function interpolateLine(prev: [number, number][], next: [number, number][], t: number): [number, number][] {
  if (t <= 0) return prev;
  if (t >= 1) return next;
  const maxLen = Math.max(prev.length, next.length);
  if (maxLen === 0) return prev;
  const result: [number, number][] = [];
  for (let i = 0; i < maxLen; i++) {
    const prevIdx = Math.min(i / Math.max(1, maxLen - 1) * (prev.length - 1), prev.length - 1);
    const nextIdx = Math.min(i / Math.max(1, maxLen - 1) * (next.length - 1), next.length - 1);
    const pLow = Math.floor(prevIdx);
    const pHigh = Math.min(pLow + 1, prev.length - 1);
    const pFrac = prevIdx - pLow;
    const pLat = lerp(prev[pLow][0], prev[pHigh][0], pFrac);
    const pLng = lerp(prev[pLow][1], prev[pHigh][1], pFrac);
    const nLow = Math.floor(nextIdx);
    const nHigh = Math.min(nLow + 1, next.length - 1);
    const nFrac = nextIdx - nLow;
    const nLat = lerp(next[nLow][0], next[nHigh][0], nFrac);
    const nLng = lerp(next[nLow][1], next[nHigh][1], nFrac);
    result.push([lerp(pLat, nLat, t), lerp(pLng, nLng, t)]);
  }
  return result;
}

export function interpolateFrontLine(date: Date): FrontLineData {
  const sorted = [...frontLineData].sort((a, b) => a.date.getTime() - b.date.getTime());
  if (date.getTime() <= sorted[0].date.getTime()) return sorted[0];
  if (date.getTime() >= sorted[sorted.length - 1].date.getTime()) return sorted[sorted.length - 1];
  let prev = sorted[0], next = sorted[sorted.length - 1];
  for (let i = 0; i < sorted.length - 1; i++) {
    if (sorted[i].date.getTime() <= date.getTime() && sorted[i + 1].date.getTime() >= date.getTime()) {
      prev = sorted[i]; next = sorted[i + 1]; break;
    }
  }
  if (prev.date.getTime() === date.getTime()) return prev;
  if (next.date.getTime() === date.getTime()) return next;
  const totalSpan = next.date.getTime() - prev.date.getTime();
  const elapsed = date.getTime() - prev.date.getTime();
  const t = totalSpan > 0 ? elapsed / totalSpan : 0;
  return { date, line: interpolateLine(prev.line, next.line, t) };
}
